"""Index and extract assets from the project's source ZIPs (read-only; stdlib only).

  python -I Tools/asset_index.py build                     # writes Docs/ASSET_INDEX.md + Docs/asset_index.json
  python -I Tools/asset_index.py find lamp                 # search names/categories
  python -I Tools/asset_index.py get "light-*" --pack roads --to <NEW_EMPTY_DIR> [--fmt glb|fbx|obj]

ZIP contents are untrusted: nothing is executed, paths are sanitized, `get` refuses non-empty targets.
ponytail: category = first '-' token of the model name (Kenney convention); add a map if a pack breaks it.
"""
import argparse, fnmatch, json, re, sys, zipfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ["3d model enviroment/*.zip", "3d model charater/*.zip", "ArtSource/ThirdParty/CC0/*/*.zip"]
JSON_OUT, MD_OUT = ROOT / "Docs/asset_index.json", ROOT / "Docs/ASSET_INDEX.md"
FMT_DIR = {"fbx": "FBX format", "glb": "GLB format", "obj": "OBJ format"}
# Packs whose ZIP carries no license text: values taken from Docs/ASSET_REGISTER.csv.
KNOWN_LICENSE = {
    "asphalt_01_4k.blend.zip": "CC0-1.0 (Poly Haven)",
    "japanese_street_at_night.zip": "CC-BY-4.0 + unresolved author terms (reference only)",
}


def pack_info(zf, name):
    if name.startswith("SORA_"):
        lic, scope = "PRIVATE (AFX-derived); never publish", "private"
    elif "charater" in name or name in CHAR_ZIPS:
        lic, scope = "IP/license unverified; local only", "restricted"
    elif name in KNOWN_LICENSE:
        lic, scope = KNOWN_LICENSE[name], "restricted" if "AFX" in name or "japanese" in name else "public"
    else:
        txt = zf.read("License.txt").decode("utf8", "ignore") if "License.txt" in zf.namelist() else ""
        lic, scope = ("CC0-1.0", "public") if "CC0" in txt else ("UNVERIFIED", "restricted")
    return lic, scope


CHAR_ZIPS = set()


def build():
    packs = []
    for pattern in SOURCES:
        for path in sorted(ROOT.glob(pattern)):
            if path.stat().st_size < 1024:  # git-lfs pointer stub, not a real ZIP
                continue
            try:
                zf = zipfile.ZipFile(path)
            except zipfile.BadZipFile:
                print("skip (bad zip):", path, file=sys.stderr)
                continue
            with zf:
                if "charater" in str(path):
                    CHAR_ZIPS.add(path.name)
                lic, scope = pack_info(zf, path.name)
                items = defaultdict(lambda: {"formats": {}, "bytes": 0})
                for i in zf.infolist():
                    if i.is_dir():
                        continue
                    p = Path(i.filename)
                    ext = p.suffix.lower().lstrip(".")
                    if ext not in ("fbx", "glb", "gltf", "obj", "blend", "usdz", "png", "jpg", "exr", "mtl") or \
                       "Preview" in i.filename or "Sample" in i.filename:
                        continue
                    if "Textures" in p.parts or ext in ("mtl",):
                        continue  # textures are bundled by `get`, not catalogued
                    e = items[p.stem]
                    e["formats"][ext] = i.filename
                    e["bytes"] += i.file_size
                models = []
                for stem, e in sorted(items.items()):
                    models.append({"name": stem, "category": stem.split("-")[0].split("_")[0].lower(),
                                   "formats": e["formats"], "bytes": e["bytes"]})
                packs.append({"zip": str(path.relative_to(ROOT)).replace("\\", "/"), "pack": path.stem,
                              "license": lic, "scope": scope, "zip_bytes": path.stat().st_size,
                              "models": models})
    JSON_OUT.write_text(json.dumps({"packs": packs}, indent=1, ensure_ascii=False), encoding="utf8")
    write_md(packs)
    total = sum(len(p["models"]) for p in packs)
    # self-check: every catalogued path really exists in its zip
    for p in packs:
        with zipfile.ZipFile(ROOT / p["zip"]) as zf:
            names = set(zf.namelist())
            assert all(f in names for m in p["models"] for f in m["formats"].values()), p["zip"]
    print(f"indexed {len(packs)} packs, {total} entries -> {MD_OUT.relative_to(ROOT)}")


def write_md(packs):
    L = ["# Asset index (generated)", "",
         "Generated by `python -I Tools/asset_index.py build`. Do not edit by hand.",
         "Extract: `python -I Tools/asset_index.py get \"<glob>\" --pack <pack> --to <NEW_EMPTY_DIR>`", "",
         "| Pack | Scope | License | Entries | ZIP MB |", "|---|---|---|---:|---:|"]
    for p in packs:
        L.append(f"| `{p['pack']}` | {p['scope']} | {p['license']} | {len(p['models'])} | {p['zip_bytes']/1e6:.1f} |")
    for p in packs:
        L += ["", f"## {p['pack']}", f"`{p['zip']}` — {p['license']}", ""]
        cats = defaultdict(list)
        for m in p["models"]:
            cats[m["category"]].append(m["name"])
        for c, names in sorted(cats.items()):
            L.append(f"- **{c}** ({len(names)}): " + ", ".join(names))
    MD_OUT.write_text("\n".join(L) + "\n", encoding="utf8")


def load():
    if not JSON_OUT.exists():
        sys.exit("run `build` first")
    return json.loads(JSON_OUT.read_text(encoding="utf8"))["packs"]


def match(packs, pat, pack=None):
    pat = pat.lower()
    for p in packs:
        if pack and pack.lower() not in p["pack"].lower():
            continue
        for m in p["models"]:
            if fnmatch.fnmatch(m["name"].lower(), pat if "*" in pat else f"*{pat}*") or m["category"] == pat:
                yield p, m


def find(a):
    for p, m in match(load(), a.query, a.pack):
        print(f"{p['pack']:40} {m['category']:12} {m['name']:32} {','.join(m['formats'])}")


def get(a):
    dest = Path(a.to).resolve()
    if dest.exists() and any(dest.iterdir()):
        sys.exit(f"{dest} must be new or empty")
    dest.mkdir(parents=True, exist_ok=True)
    n = 0
    for p, m in match(load(), a.query, a.pack):
        if p["scope"] != "public" and not a.allow_restricted:
            print(f"skip {m['name']}: pack scope={p['scope']} (use --allow-restricted for local-only use)")
            continue
        src = m["formats"].get(a.fmt) or next(iter(m["formats"].values()))
        with zipfile.ZipFile(ROOT / p["zip"]) as zf:
            out_dir = dest / p["pack"]
            todo = [src]
            # bundle shared textures once per pack (Kenney models reference Textures/colormap.png)
            todo += [n for n in zf.namelist() if "/Textures/" in n and not n.endswith("/")
                     and not (out_dir / Path(n).name).exists()]
            for name in todo:
                rel = Path(name)
                if rel.is_absolute() or ".." in rel.parts:
                    continue
                target = out_dir / ("Textures" if "Textures" in rel.parts else "") / rel.name
                target.parent.mkdir(parents=True, exist_ok=True)
                if not target.exists():
                    target.write_bytes(zf.read(name))
        n += 1
    print(f"extracted {n} models to {dest}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("build")
    f = sp.add_parser("find"); f.add_argument("query"); f.add_argument("--pack")
    g = sp.add_parser("get"); g.add_argument("query"); g.add_argument("--pack")
    g.add_argument("--to", required=True); g.add_argument("--fmt", default="glb", choices=FMT_DIR)
    g.add_argument("--allow-restricted", action="store_true")
    a = ap.parse_args()
    {"build": lambda _: build(), "find": find, "get": get}[a.cmd](a)
